c = Board("ai-lab-cost", "AI Lab — Cost per token", ["ai-lab", "cost", "opencost"], [])
c.row("GPU spend")
c.panel("GPU $/h by namespace", [("ai_lab:gpu_cost_per_hour:by_namespace", "{{namespace}}")], "currencyUSD", w=12)
c.panel("GPU $/h by model", [("ai_lab:gpu_cost_per_hour:by_model", "{{model_name}}")], "currencyUSD", w=12)
c.row("Unit economics")
c.panel("$ per 1M output tokens", [("ai_lab:cost_per_1m_output_tokens:by_model", "{{model_name}}")], "currencyUSD", w=12,
        desc="GPU cost of the model's pods / generated tokens. Idle replicas make this explode — that's the point.")
