C = 'cluster_queue=~"$cq"'
k.row("Kueue")
k.panel("Pending workloads", [(f'sum by (cluster_queue, status) (kueue_pending_workloads{{{C}}})', "{{cluster_queue}} {{status}}")],
        desc="status=active: waiting for quota; inadmissible: can never fit as configured.")
k.panel("Admitted active workloads", [(f'sum by (cluster_queue) (kueue_admitted_active_workloads{{{C}}})', "{{cluster_queue}}")])
k.panel("GPU quota usage", [
    (f'sum by (cluster_queue) (kueue_cluster_queue_resource_usage{{{C}, resource="nvidia.com/gpu"}})', "used {{cluster_queue}}"),
    (f'sum by (cluster_queue) (kueue_cluster_queue_nominal_quota{{{C}, resource="nvidia.com/gpu"}})', "nominal {{cluster_queue}}")],
    desc="usage > nominal means the queue is borrowing from its cohort.")
k.panel("Admission wait p90", [
    (f'histogram_quantile(0.9, sum by (le, cluster_queue) (rate(kueue_admission_wait_time_seconds_bucket{{{C}}}[30m])))', "{{cluster_queue}}")], "s")
k.panel("Preemptions / evictions", [
    (f'sum by (cluster_queue, reason) (increase(kueue_evicted_workloads_total{{{C}}}[1h]))', "{{cluster_queue}} {{reason}}")])
k.panel("Quota borrowing", [
    (f'sum by (cluster_queue) (kueue_cluster_queue_borrowing_limit{{{C}, resource="nvidia.com/gpu"}})', "{{cluster_queue}} limit")],
    desc="Metric availability depends on Kueue version / metrics.enableClusterQueueResources.")
k.row("Autoscaling (KEDA → HPA)")
k.panel("Current vs desired replicas", [
    ('kube_horizontalpodautoscaler_status_current_replicas{namespace="llm-serving"}', "current {{horizontalpodautoscaler}}"),
    ('kube_horizontalpodautoscaler_status_desired_replicas{namespace="llm-serving"}', "desired {{horizontalpodautoscaler}}")], w=12,
    desc="desired > current for long = pods stuck Pending (no GPUs) or slow cold starts.")
k.panel("GPU requests: allocated vs allocatable", [
    ('sum(kube_pod_container_resource_requests{resource="nvidia_com_gpu"} * on (namespace, pod) group_left() (kube_pod_status_phase{phase="Running"} == 1)) by (namespace)', "{{namespace}}"),
    ('sum(kube_node_status_allocatable{resource="nvidia_com_gpu"})', "allocatable")], w=12)

